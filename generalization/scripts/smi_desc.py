def smi_aggregate(comp_dict):
    comp_smi = {}
    for c, amt in comp_dict.items():
        if amt is None or (isinstance(amt, float) and np.isnan(amt)) or amt <= 0: continue
        code = str(c).strip()
        if code in CODE_DESC: comp_smi[code] = float(amt)
    if not comp_smi: return {}
    total = sum(comp_smi.values())
    all_keys = set()
    for code in comp_smi: all_keys.update(CODE_DESC[code].keys())
    agg = {}
    for k in all_keys:
        vals, ws = [], []
        for code, amt in comp_smi.items():
            if k in CODE_DESC[code] and not (isinstance(CODE_DESC[code][k], float) and np.isnan(CODE_DESC[code][k])):
                vals.append(CODE_DESC[code][k]); ws.append(amt/total)
        if not vals: continue
        ws = np.array(ws)/np.sum(ws); vv = np.array(vals)
        agg[f"wmean_{k}"] = float(np.average(vv, weights=ws))
        agg[f"wstd_{k}"] = float(np.sqrt(np.average((vv-agg[f"wmean_{k}"])**2, weights=ws))) if len(vv)>1 else 0.0
    return agg

