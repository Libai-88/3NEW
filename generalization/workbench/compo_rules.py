def apply(mat):
    """对 mat(code->dict) 就地应用组成覆盖；返回被改动的 code 列表。"""
    changed = []
    for code, ov in OVERRIDES.items():
        src = 'COMPO_RULES'
        if code not in mat:
            continue  # 未在库中则不新增，避免凭空造原料
        m = mat[code]
        merge = False
        for k, v in ov.items():
            if m.get(k) != v:
                m[k] = v
                merge = True
        if merge:
            m['数据来源'] = src
            m['备注'] = SOURCE_TEXT.get(code, '')
            m['依据'] = COMPO.get(code, (None,)[1:])[-1] if code in COMPO else '推断'
            changed.append(code)
    return changed


